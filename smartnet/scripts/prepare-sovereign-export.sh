#!/usr/bin/env bash
# Phase 6: list paths required for a sovereign SmartNet repo export (no copy performed).
# No docs/ tree is assumed; workspace paths are checked by scripts/verify-sovereign-workspace.sh.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
OUT="${1:-$ROOT/target/sovereign-export-manifest.txt}"
mkdir -p "$(dirname "$OUT")"

python3 << 'PY' > "$OUT"
import re
from pathlib import Path

root = Path(".")
cargo = (root / "Cargo.toml").read_text()
members: list[str] = []
in_members = False
for line in cargo.splitlines():
    if line.strip() == "members = [":
        in_members = True
        continue
    if in_members:
        if line.strip() == "]":
            break
        m = re.search(r'"([^"]+)"', line)
        if m:
            members.append(m.group(1))

root_files = [
    "Cargo.toml",
    "Cargo.lock",
    "Makefile",
    "deny.toml",
    "rustfmt.toml",
    "README.md",
    "AGENTS.md",
    "current-state.txt",
    "next-state.txt",
    "LICENSE-APACHE",
    "LICENSE-MIT",
]

print("# SmartNet sovereign export manifest (Phase 6)")
print("# Generated by scripts/prepare-sovereign-export.sh")
print("# Copy paths relative to repo root into new git root.")
print()
print("## Root files")
for f in root_files:
    if (root / f).exists():
        print(f)
print()
print(f"## workspace.members ({len(members)} paths)")
for m in members:
    print(m)
PY

echo "Wrote $OUT ($(wc -l < "$OUT") lines)"
./scripts/verify-sovereign-workspace.sh
